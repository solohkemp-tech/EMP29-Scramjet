import { createInterface } from 'node:readline/promises';
import { Writable } from 'node:stream';
import { access, copyFile, writeFile, rename } from 'node:fs/promises';
import { hashPassword } from '../lib/auth.mjs';
class Output extends Writable { muted=false; _write(chunk,_encoding,callback){if(!this.muted)process.stdout.write(chunk);callback();} }
const output=new Output();const rl=createInterface({input:process.stdin,output,terminal:!!process.stdin.isTTY});
async function secret(prompt){process.stdout.write(prompt);output.muted=true;try{return await rl.question('');}finally{output.muted=false;process.stdout.write('\n');}}
try{
  console.log('EMP29 / Initial setup');
  const exists=await access('.env').then(()=>true,()=>false);
  if(exists&&(await rl.question('A .env already exists. Back it up and replace it? [y/N] ')).trim().toLowerCase()!=='y'){rl.close();process.exit(0);}
  let origin=(await rl.question('Public HTTPS origin (example: https://emp29.example.com; blank for localhost): ')).trim();
  if(origin){const url=new URL(origin);if(url.protocol!=='https:'||url.username||url.password||url.pathname!=='/'||url.search||url.hash)throw new Error('Enter an HTTPS origin without a path or credentials.');origin=url.origin;}
  const port=Number((await rl.question('Local port [3030]: ')).trim()||3030);
  if(!Number.isInteger(port)||port<1024||port>65535)throw new Error('Port must be between 1024 and 65535.');
  const password=await secret('Choose an access password (at least 12 characters): ');
  if(password.length<12||password.length>512)throw new Error('Password must be between 12 and 512 characters.');
  if(await secret('Repeat the password: ')!==password)throw new Error('Passwords did not match.');
  const contents=`# Generated by EMP29 setup; keep this file private.\nHOST=127.0.0.1\nPORT=${port}\nEMP29_ORIGIN=${origin}\nTRUST_PROXY=${!!origin}\nEMP29_PASSWORD_HASH=${hashPassword(password)}\nEMP29_MAX_CONNECTIONS=20\n`;
  if(exists)await copyFile('.env',`.env.backup-${Date.now()}`);
  await writeFile('.env.tmp',contents,{mode:0o600});await rename('.env.tmp','.env');
  console.log(`Setup saved. Run npm start. ${origin?'Point your HTTPS reverse proxy to 127.0.0.1:'+port:'Open http://localhost:'+port}`);
}catch(error){console.error(error.message);process.exitCode=1;}finally{rl.close();}
